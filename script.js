function selectCapability(key, moveFocus = false) {
  const capability = capabilities[key];
  const activeTab = tabs.find((tab) => tab.dataset.capability === key);
  const activeIndex = capabilityOrder.indexOf(key);

  if (!capability || !activeTab) {
    return;
  }

  tabs.forEach((tab) => {
    const isActive = tab === activeTab;
    tab.classList.toggle("is-active", isActive);
    tab.setAttribute("aria-selected", String(isActive));
    tab.tabIndex = isActive ? 0 : -1;
  });

  detailPanel.setAttribute("aria-labelledby", activeTab.id);
  detailKicker.textContent = capability.label;
  detailTitle.textContent = capability.title;
  detailSummary.textContent = capability.summary;
  detailCount.textContent = `${String(activeIndex + 1).padStart(2, "0")} / ${String(capabilityOrder.length).padStart(2, "0")}`;
  detailContent.innerHTML = key === "social"
    ? socialDetailMarkup(capability)
    : standardDetailMarkup(capability);

  if (moveFocus) {
    activeTab.focus();
  }
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => selectCapability(tab.dataset.capability));
  tab.addEventListener("keydown", (event) => {
    const currentIndex = capabilityOrder.indexOf(tab.dataset.capability);
    let nextIndex = currentIndex;

    if (event.key === "ArrowRight" || event.key === "ArrowDown") {
      nextIndex = (currentIndex + 1) % capabilityOrder.length;
    } else if (event.key === "ArrowLeft" || event.key === "ArrowUp") {
      nextIndex = (currentIndex - 1 + capabilityOrder.length) % capabilityOrder.length;
    } else if (event.key === "Home") {
      nextIndex = 0;
    } else if (event.key === "End") {
      nextIndex = capabilityOrder.length - 1;
    } else {
      return;
    }

    event.preventDefault();
    selectCapability(capabilityOrder[nextIndex], true);

    if (window.matchMedia("(max-width: 920px)").matches) {
      detailPanel.scrollIntoView({
        behavior: reduceMotion.matches ? "auto" : "smooth",
        block: "start"
      });
    }
  });
});

detailContent.addEventListener("click", (event) => {
  const trigger = event.target.closest("[data-open-evidence]");
  if (!trigger) {
    return;
  }

  lastEvidenceTrigger = trigger;
  evidenceDialog.showModal();
});

dialogClose.addEventListener("click", () => evidenceDialog.close());

evidenceDialog.addEventListener("click", (event) => {
  if (event.target === evidenceDialog) {
    evidenceDialog.close();
  }
});

evidenceDialog.addEventListener("close", () => {
  if (lastEvidenceTrigger) {
    lastEvidenceTrigger.focus();
  }
});

document.getElementById("print-resume").addEventListener("click", () => {
  if (evidenceDialog.open) {
    evidenceDialog.close();
  }
  window.print();
});

const navLinks = Array.from(document.querySelectorAll(".main-nav a"));
const navSections = navLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

if ("IntersectionObserver" in window) {
  const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) {
        return;
      }

      navLinks.forEach((link) => {
        link.classList.toggle("is-active", link.getAttribute("href") === `#${entry.target.id}`);
      });
    });
  }, {
    rootMargin: "-30% 0px -58% 0px",
    threshold: 0
  });

  navSections.forEach((section) => sectionObserver.observe(section));
}

